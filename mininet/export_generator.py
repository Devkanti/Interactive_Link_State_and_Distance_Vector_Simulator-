#!/usr/bin/env python3
"""
export_generator.py
===================
Generates fully functional, standalone Mininet Python emulation scripts
from any dynamic network topology (JSON nodes and links).

The generated script can be executed on any Ubuntu/Debian/WSL Linux machine:
    sudo python3 custom_mininet_topo.py
"""

def generate_mininet_script(nodes, edges, default_protocol="LSR"):
    """
    Generates executable Mininet Python code matching the input graph.
    """
    node_lines = []
    link_lines = []
    subnet_counter = 1

    # Map router names to friendly variable names (r1, r2, ...)
    node_var_map = {}
    for idx, n in enumerate(nodes):
        raw_id = str(n.get("id", f"r{idx+1}")).lower().replace(" ", "_")
        var_name = raw_id if raw_id.isalnum() else f"r{idx+1}"
        node_var_map[n.get("id")] = var_name
        label = n.get("label", var_name)
        node_lines.append(f"    # Router {label}\n    {var_name} = net.addHost('{var_name}', cls=LinuxRouter, ip='10.{idx+1}.0.1/16')")

    # Links with dedicated point-to-point subnets: 10.0.{subnet}.1/24 and 10.0.{subnet}.2/24
    for idx, e in enumerate(edges):
        src_id = e.get("source")
        dst_id = e.get("target")
        src_var = node_var_map.get(src_id)
        dst_var = node_var_map.get(dst_id)
        cost = e.get("cost", 1)

        if src_var and dst_var:
            s_num = subnet_counter
            subnet_counter += 1
            link_lines.append(
                f"    # Link {src_var} <-> {dst_var} (Cost: {cost}, Subnet: 10.0.{s_num}.0/24)\n"
                f"    link_{src_var}_{dst_var} = net.addLink({src_var}, {dst_var},\n"
                f"        params1={{'ip': '10.0.{s_num}.1/24'}},\n"
                f"        params2={{'ip': '10.0.{s_num}.2/24'}}\n"
                f"    )"
            )

    nodes_str = "\n".join(node_lines)
    links_str = "\n".join(link_lines)
    router_list_str = ", ".join(node_var_map.values())

    script = f'''#!/usr/bin/env python3
"""
custom_mininet_topo.py
======================
Auto-generated by Interactive Link State & Distance Vector Simulator.
Emulates real Linux network namespaces and kernel routing tables.

Prerequisites:
    sudo apt-get install mininet iproute2
Execution:
    sudo python3 custom_mininet_topo.py
"""

from mininet.net import Mininet
from mininet.node import Node, Host
from mininet.cli import CLI
from mininet.log import setLogLevel, info
import sys
import time

class LinuxRouter(Node):
    """A Node with IP forwarding enabled, behaving as a real Layer 3 Linux Router."""
    def config(self, **params):
        super(LinuxRouter, self).config(**params)
        # Enable IPv4 forwarding across network namespace interfaces
        self.cmd('sysctl -w net.ipv4.ip_forward=1')

    def terminate(self):
        self.cmd('sysctl -w net.ipv4.ip_forward=0')
        super(LinuxRouter, self).terminate()

def run_topology():
    setLogLevel('info')
    info('*** Initializing Mininet Layer 3 Router Topology\\n')
    net = Mininet(controller=None)

    info('*** Adding Linux Routers\\n')
{nodes_str}

    info('*** Creating Virtual Ethernet Point-to-Point Links\\n')
{links_str}

    info('*** Starting Network\\n')
    net.start()

    routers = [{router_list_str}]

    info('\\n=================================================================\\n')
    info('  MININET ROUTER EMULATION READY!\\n')
    info('  Active Protocol: {default_protocol}\\n')
    info('  Try commands:\\n')
    info('    mininet> {list(node_var_map.values())[0]} ip route show\\n')
    info('    mininet> pingall\\n')
    info('    mininet> link {list(node_var_map.values())[0]} {list(node_var_map.values())[1] if len(node_var_map) > 1 else "r1"} down\\n')
    info('=================================================================\\n\\n')

    CLI(net)

    info('*** Stopping Network\\n')
    net.stop()

if __name__ == '__main__':
    run_topology()
'''
    return script

if __name__ == "__main__":
    # Test generation
    sample_nodes = [{"id": "r1", "label": "Router 1"}, {"id": "r2", "label": "Router 2"}, {"id": "r3", "label": "Router 3"}]
    sample_edges = [{"source": "r1", "target": "r2", "cost": 1}, {"source": "r2", "target": "r3", "cost": 2}]
    print(generate_mininet_script(sample_nodes, sample_edges))
